export function makeHelpers(lang) {
  const t = TXT[lang] || TXT.uz;
  // unitRaw: katalogdagi game.unit ("110" kabi faqat raqamli nomlarga birlik qo'shiladi)
  const parse = (name, unitRaw) => {
    const raw = String(name || "").trim();
    const full = unitRaw && /^\d[\d\s.,]*$/.test(raw) ? `${raw} ${unitRaw}` : raw;
    const m = full.match(/^([\d\s.,+]+)\s+(UC|Diamonds|Gold|Delta Coins|BC|Tokens|Bonds|Robux)$/i);
    if (!m) return null;
    const key = Object.keys(t.unit).find((k) => k.toLowerCase() === m[2].toLowerCase()) || m[2];
    return { qty: m[1].trim(), unit: t.unit[key] || m[2] };
  };
  const tr = (name) => {
    for (const [re, to] of t.names) if (re.test(name)) return String(name).replace(re, to);
    return String(name || "");
  };
  const pretty = (name, unitRaw) => {
    const p = parse(name, unitRaw);
    return p ? `${p.qty} ${p.unit}` : tr(name);
  };
  return { t, parse, tr, pretty };
}
